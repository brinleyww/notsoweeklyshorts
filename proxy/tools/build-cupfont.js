// Builds proxy/src/cupfont.js, the Forced Square outlines the cup link card draws with
// (src/cupcard.js), from the game's own forced_square.json:
//   node tools/build-cupfont.js
// The font has only straight segments, so each glyph is a list of closed polygons.
const fs = require("fs");
const path = require("path");

const GAME = path.resolve(__dirname, "../..");
const OUT = path.resolve(__dirname, "../src/cupfont.js");

const font = JSON.parse(fs.readFileSync(path.join(GAME, "forced_square.json"), "utf8"));
const units = font.resolution;
if (!Number.isFinite(units)) throw new Error("no resolution in forced_square.json");

const lines = [];
for (const [ch, glyph] of Object.entries(font.glyphs)) {
    if (ch.length !== 1 || ch === "\n" || ch === "\t") continue;
    const parts = String(glyph.o || "").trim().split(/\s+/).filter(Boolean);
    for (const token of parts) {
        if (/^-?\d+$/.test(token) || ["m", "l", "z"].includes(token)) continue;
        throw new Error(`glyph ${ch}: unsupported path command "${token}"`);
    }
    lines.push(ch + "\t" + Math.round(glyph.ha) + "\t" + parts.join(" "));
}
lines.sort();

const text = `// Generated by tools/build-cupfont.js from forced_square.json. Do not edit.
// One line per glyph: the character, its advance, then its outline in font units (y up),
// as "m x y" (start a contour) and "l x y" (a corner); "z" closes it. src/cupcard.js draws them.
export const FONT_UNITS = ${units};
export const FONT_ASCENDER = ${Math.round(font.ascender)};
export const FONT = ${JSON.stringify(lines.join("\n"))};
`;
fs.writeFileSync(OUT, text);
console.log(`${lines.length} glyphs, ${(text.length / 1024).toFixed(1)} kB -> ${path.relative(GAME, OUT)}`);
